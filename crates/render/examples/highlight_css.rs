//! Prints the stylesheet for highlighted code (light and dark themes).
//! Regenerate with:
//! `cargo run -p render --example highlight_css > crates/server/static/highlight.css`

use syntect::highlighting::ThemeSet;
use syntect::html::{ClassStyle, css_for_theme_with_class_style};

fn main() {
    let themes = ThemeSet::load_defaults();
    let light =
        css_for_theme_with_class_style(&themes.themes["InspiredGitHub"], ClassStyle::Spaced)
            .expect("light theme");
    let dark =
        css_for_theme_with_class_style(&themes.themes["base16-ocean.dark"], ClassStyle::Spaced)
            .expect("dark theme");
    println!("/* Generated by `cargo run -p render --example highlight_css`. */");
    println!("{light}");
    println!("@media (prefers-color-scheme: dark) {{\n{dark}\n}}");
}
